"""Generate core/data/.../SiteCatalog.kt.

Inputs (pass the directory holding them):
  nexrad_common.py           ARM-DOE/pyart pyart/io/nexrad_common.py (NEXRAD_LOCATIONS)
  RadarNexradStations.xml    Unidata/tds test content (station names)
  OPERA_RADARS.csv           EUMETNET/openradardata-validator stations list
  ord_ids.txt                ODIM codes published on the Open Radar Data API
"""
import ast, csv, sys, math, xml.etree.ElementTree as ET
S = sys.argv[1]
locs = None
for n in ast.parse(open(f"{S}/nexrad_common.py").read()).body:
    if isinstance(n, ast.Assign) and getattr(n.targets[0], 'id', '') == 'NEXRAD_LOCATIONS':
        locs = ast.literal_eval(n.value)
names = {}
for st in ET.parse(f"{S}/RadarNexradStations.xml").getroot().iter('station'):
    l = st.find('location3D')
    names[st.get('value')] = (st.get('name'), st.get('state'), float(l.get('latitude')), float(l.get('longitude')))

def pretty(nm, state):
    first = nm.split('/')[0].replace('_', ' ').strip().lower()
    first = ' '.join(w.capitalize() for w in first.split())
    return f"{first}, {state}" if state and state not in ('XX', '') else first

def num(s):
    try: return float(s)
    except (TypeError, ValueError): return None

out = []
for icao, d in sorted(locs.items()):
    if not (icao.startswith('K') or icao.startswith('P') or icao == 'TJUA'):
        continue
    nm = None
    n2 = names.get(icao[1:])
    if n2 and math.hypot(n2[2] - d['lat'], n2[3] - d['lon']) < 0.5:
        nm = pretty(n2[0], n2[1])
    if nm is None:
        for n3 in names.values():
            if math.hypot(n3[2] - d['lat'], n3[3] - d['lon']) < 0.15:
                nm = pretty(n3[0], n3[1]); break
    if nm is None:
        continue  # not an operational WSR-88D in the Level II feed
    out.append(('NEXRAD', icao, nm, d['lat'], d['lon'], ''))

rows = {r['ODIM code']: r for r in csv.DictReader(open(f"{S}/OPERA_RADARS.csv", encoding='utf-8-sig'))}
# Spain publishes on the Open Radar Data API under newer ODIM codes than the CSV;
# positions and names from the API's /locations (Oct 2026), matching the CSV sites.
OVERRIDES = {
    'esahr': ('Alhaurin el Grande (Malaga)', 'Spain', 36.61343, -4.65933),
    'esatn': ('Artenara (Gran Canaria)', 'Spain', 28.01879, -15.61454),
    'esclg': ('Castillo las Guardas (Sevilla)', 'Spain', 37.68868, -6.33308),
    'esgld': ('Gelida (Barcelona)', 'Spain', 41.40818, 1.88489),
    'esnjr': ('Nijar (Almeria)', 'Spain', 36.83243, -2.08210),
    'espdg': ('Perdiguera (Zaragoza)', 'Spain', 41.73399, -0.54594),
    'essft': ('Sierra de Fuentes (Caceres)', 'Spain', 39.42883, -6.28528),
    'estjv': ('Torrejon de Velasco (Madrid)', 'Spain', 40.17592, -3.71368),
}
for code, (loc, country, la, lo) in OVERRIDES.items():
    rows[code] = {'Location': loc, 'Country': country, 'Latitude': la, 'Longitude': lo}
skipped = []
for code in open(f"{S}/ord_ids.txt").read().split():
    r = rows.get(code)
    lat, lon = (num(r['Latitude']), num(r['Longitude'])) if r else (None, None)
    if lat is None or lon is None:
        skipped.append(code); continue
    out.append(('OPERA', code, f"{r['Location'].strip()}, {r['Country'].strip()}", lat, lon, code[:2].upper()))

def esc(s): return s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$')
print('''package app.hookline.radar.core.data

// GENERATED by tools/sites/generate_sites.py from Py-ART NEXRAD_LOCATIONS and
// Unidata RadarNexradStations.xml (US), and EUMETNET OPERA_RADARS.csv filtered
// to radars published on the Open Radar Data API (Europe). Do not edit by hand.

/** Which data network serves a radar. */
enum class Network { NEXRAD, OPERA }

/** Every radar with open single-site data that Hookline can stream. */
object SiteCatalog {
    val ALL: List<RadarSite> = listOf(''')
for net, sid, nm, lat, lon, cc in out:
    print(f'        RadarSite("{sid}", "{esc(nm)}", LatLon({lat:.5f}, {lon:.5f}), Network.{net}, "{cc}"),')
print('''    )
}''')
print(f"{sum(o[0]=='NEXRAD' for o in out)} NEXRAD + {sum(o[0]=='OPERA' for o in out)} OPERA; skipped: {skipped}", file=sys.stderr)
